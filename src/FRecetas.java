    private void btnInsertActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInsertActionPerformed
      try {
        Object[] res = cnx.ejecutarCRUDSinSalida(
            "insertar_receta",
            new Object[]{
                Integer.parseInt(txtNumero.getText()),
                txtFecha.getText(),      
                txtVigencia.getText(),   
                txtEstado.getText(),     
                Integer.parseInt(txtFolio.getText())
            }
        );
        JOptionPane.showMessageDialog(this, "Estado: " + res[0] + "\nMensaje: " + res[1]);
        if (Integer.parseInt(res[0].toString()) == 1) {
            cnx.entablar(todo, jTable);
        }
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "El folio debe ser un número");
    }
    }//GEN-LAST:event_btnInsertActionPerformed

