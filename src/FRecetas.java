    private void jTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableMouseClicked
       int f = jTable.getSelectedRow();
    if (f < 0) {
        return;
    }

    txtNumero.setText(String.valueOf(jTable.getValueAt(f, 0)));

    
    String fecha = String.valueOf(jTable.getValueAt(f, 1));
    if (fecha.length() > 19) {
        fecha = fecha.substring(0, 19);
    }
    txtFecha.setText(fecha);

    txtVigencia.setText(String.valueOf(jTable.getValueAt(f, 2)));
    txtEstado.setText(String.valueOf(jTable.getValueAt(f, 3)));
    txtFolio.setText(String.valueOf(jTable.getValueAt(f, 4)));
    }//GEN-LAST:event_jTableMouseClicked

